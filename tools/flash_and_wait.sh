#!/bin/sh
# ===========================================================================
#  焼いて、USB が戻るまで待って、安定した名前を張る (docs D50)
# ===========================================================================
#  VS Code の「Shizuku: 焼く」タスクと F5 (launch.json) の両方がこれを使う。
#  素の `bazelisk run //firmware:flash` では踏む穴が 3 つあり、どれも
#  「焼けていないのに焼けていないように見えない」形で出るので、ここへ閉じ込める。
set -u

PORT_GLOB='/dev/cu.usbmodem*'
GDB_LINK=/tmp/shizuku-gdb-port
DIAG_LINK=/tmp/shizuku-diag-port

# ---------------------------------------------------------------------------
# 1) ポートを掴んだままの gdb を始末する
# ---------------------------------------------------------------------------
# ★★VS Code のデバッグを止めても `arm-none-eabi-gdb --interpreter=mi` が
#   **生き残ってポートを掴んだまま**になることがある (2026-08-24 実測: PID が
#   残り /dev/cu.usbmodem1103 を保持していた)。こうなると
#     - picotool が焼けない
#     - 次に繋いだ GDB が化けた応答を受け取る (2 つが同じ線に乗るため)
#   ★**SIGTERM では死なない**ことも実測した。SIGKILL で止める。
#   ★殺すのは gdb だけ。他のプロセス (VS Code のシリアルモニタ等) は
#     名前を出して**手で閉じてもらう** — エディタごと殺しては元も子もない。
holders=$(lsof -t ${PORT_GLOB} /dev/tty.usbmodem* 2>/dev/null | sort -u)
for pid in ${holders}; do
  name=$(ps -p "${pid}" -o comm= 2>/dev/null)
  case "${name}" in
    *gdb*)
      echo "焼く前に: ポートを掴んだままの gdb (pid ${pid}) を止める"
      kill -9 "${pid}" 2>/dev/null
      ;;
    "")
      ;;
    *)
      echo "!! ${name} (pid ${pid}) がポートを掴んでいる — 閉じないと焼けないかもしれない"
      ;;
  esac
done

# ---------------------------------------------------------------------------
# 2) 焼く
# ---------------------------------------------------------------------------
bazelisk run //firmware:flash || exit 1

# ---------------------------------------------------------------------------
# 3) USB が戻るまで待つ
# ---------------------------------------------------------------------------
# ★★焼いた直後、デバイスノードは**約 2.8 秒まるごと消える** (2026-08-24 実測:
#   t=+6.0s に消え t=+8.8s に戻った)。picotool の終了 ≠ USB の再列挙完了。
#   ここで待たないと、preLaunchTask の直後に走る GDB が「まだ無いポート」を
#   開きに行き
#     could not open device: No such file or directory
#   で落ちる。**焼けていないのではなく、戻る前に掴みに行っただけ**。
# ★消えるのを待ってから戻るのを待つ (2 段構え)。「今ある」で判定すると
#   **再列挙前の古いノードを見て即通過**し、結局同じところで落ちる。
echo "--- USB の再列挙を待つ ---"
i=0
while [ ${i} -lt 40 ]; do
  ls ${PORT_GLOB} >/dev/null 2>&1 || break
  sleep 0.25
  i=$((i + 1))
done
i=0
while [ ${i} -lt 80 ]; do
  ls ${PORT_GLOB} >/dev/null 2>&1 && break
  sleep 0.25
  i=$((i + 1))
done
sleep 0.5

if ! ls ${PORT_GLOB} >/dev/null 2>&1; then
  echo "!! シリアルが戻ってこない (ファームが固まっている可能性)"
  exit 1
fi

# ---------------------------------------------------------------------------
# 4) 安定した名前を張る
# ---------------------------------------------------------------------------
# ★★★番号は**焼くたびに変わり得る** (usbmodem101 / usbmodem1101 を実際に
#   行き来した)。launch.json に番号を書くと必ず腐るし、聞く形にすると
#   **VS Code は ${input:} を preLaunchTask より先に解決する**ので
#   「焼く前に聞かれて、焼いた後には別物になっている」という一番困る形になる。
#   → ここで**焼いた後の実物**へシンボリックリンクを張り、launch.json は
#     その固定名だけを指す。聞かれること自体が無くなる。
#   ★GDB がシンボリックリンク越しに繋がることは実測済み。
diag=$(ls ${PORT_GLOB} | head -1)
gdb=$(ls ${PORT_GLOB} | tail -1)
ln -sf "${diag}" "${DIAG_LINK}"
ln -sf "${gdb}" "${GDB_LINK}"

echo "診断 = ${diag}  (${DIAG_LINK})"
echo "GDB  = ${gdb}  (${GDB_LINK})"
