#ifndef SHIZUKU_OBJECT_API_HPP
#define SHIZUKU_OBJECT_API_HPP
#include <cstdint>

// ===========================================================================
//  オブジェクトランドの API — カーネルオブジェクトが提供する syscall の語彙
// ===========================================================================
//  ★番号を持つのはここだけ。カーネルは番号を一切知らない (I-1) ので、この
//    ヘッダはカーネル側からは参照されない。
//  形は a0 = 番号, a1..a4 = 引数 / 戻り a0 = エラー (0 = 成功), a1 = 値。
//  ★将来 XNO (オブジェクト集合の別リポジトリ, D17) が使う公開 ABI はこれ。
//    今は internal_headers に置いているが、境界を切るときにここから公開ヘッダへ移す。
namespace shizuku {

enum struct object_api : uintptr_t {
  // オブジェクトを 1 つ作る。a1 = オブジェクト ID, a2 = main の入口,
  // a3 = object_flags のビット和。
  // ★最初のメソッドは生成側 (合成する側) が与える。オブジェクト自身はまだ一度も
  //   走っていないので自分では登録できない — 「方針は合成側」の最初の現れ。
  CREATE_OBJECT = 1,
  // メソッドから戻る。a1 = 畳む呼び出し段数 (1 = 自分だけ), a2 = 戻り値,
  // a3 = エラーコード。
  // ★★この番号は**カーネルの RETURN と同じ値**にしてある。カーネルが呼び先の lr へ
  //   載せる戻り口は常に RETURN を撃つが、同じ svc が誰から出たかで意味が変わる:
  //   ハンドラから出れば巻き戻しプリミティブ、オブジェクトから出れば経路判定で
  //   ここへ届き「メソッドが戻った」という知らせになる。だから戻り口は 1 本でよく、
  //   呼び出しごとに戻り口を指定する必要も無い。
  //   何フレーム落とすかは受けたこちらが決める (1 段 = トランポリン枠 + 呼び先枠)。
  EXIT_METHOD = 2,
  // 自分のメソッドを公開する。a1 = メソッド番号, a2 = 入口。
  // 誰のものとして登録するかは**発行元から導出**する (名乗らせない)。
  // 2 個目以降のメソッドを増やすときに使う (1 個目は CREATE_OBJECT が据える)。
  EXPORT_METHOD = 3,
  // 他オブジェクトのメソッドを呼ぶ。a1 = オブジェクト ID, a2 = メソッド番号,
  // a3 = 引数。戻り a1 = メソッドの戻り値。
  CALL_METHOD = 4,
  // 今どのオブジェクトとして走っているか / 誰に呼ばれたか。戻り a1 = オブジェクト ID。
  // ★identity はカーネルではなくカーネルオブジェクトの台帳から答える
  //   (PORT §3.1「呼び出し元 identity はカーネル支援不要」)。
  GET_CURRENT_OBJECT = 5,
  GET_CALLER_OBJECT = 6,
  // オブジェクトのメソッドを**別のスレッドとして**起動する。
  // a1 = オブジェクト ID, a2 = メソッド番号, a3 = 引数。戻り a1 = スレッド ID。
  // ★呼び出し (CALL_METHOD) と違って戻りを待たない。「イベントを待つコードを
  //   書かせない」ためには、待つ側ではなく呼ばれる側になれる必要がある (§4.3)。
  SPAWN = 7,
  // 実行権を譲る。a1 = 0 なら次の走れるスレッドへ、非 0 ならその ID へ。
  // ★借り手として走っている最中なら、これは貸し手への早期復帰になる。
  YIELD = 8,
  // 実行権を量つきで貸す。a1 = スレッド ID, a2 = **クロック数**。
  // 戻り a1 = 0 なら使い切って取り上げ、1 なら相手が自分から返した。
  // ★量は quantum ではなく安全網。正常時は相手が使い切る前に返すので発火しない。
  // ★★単位が µs ではなくクロックなのは、貸し手が縛りたいのが「どれだけ**仕事**を
  //   してよいか」だから。µs で書くと、クロックを上げた瞬間に同じ数字が黙って
  //   倍の仕事を意味するようになる。さらに機構側 (SysTick) が数えているのも
  //   クロックなので、µs で持つと装填のたびに clk_sys で割り戻すことになり、
  //   その clk_sys が貸している最中に変わらない保証は無い。
  RUN_FOR = 9,
  // 自分のスレッドを終える。a1 = 終了コード。
  EXIT_THREAD = 10,
  // 締切まで自分を走らせない。a1 = µs。**待っている間は他へ CPU を渡す**ので、
  // 「待つ」ことが他の仕事を止めない (協調の要)。
  // ★こちらは µs のまま。RUN_FOR とは**違う量**だから — あちらは仕事量、
  //   こちらは壁時計 (「20ms 後に起こして」)。単位を揃えてはいけない。
  SLEEP_US = 11,
  // スケジューラがそのスレッドへ CPU を渡すときの量 [クロック]。
  // a1 = スレッド, a2 = クロック数。
  // 0 = 量なし (バトン渡し。自分から返さないと戻ってこない = 凍結の面になる)。
  // ★これは方針。期限つきで渡す限り、自分から返さないスレッドがいても系は凍らない。
  SET_BUDGET = 12,
  // ---- メモリ (授受できる資源) ----
  // ★参照実装の「オブジェクトごとに固定の語」は簡易な一形態でしかない。ここでは
  //   大きさを指定して借り、持ち主を付け替えて渡せる形にする。持ち主が分かるので
  //   会計にも解放にも使える (DESIGN §4.1 ルール 1・3)。
  MEMORY_ALLOCATE = 13,  // a1 = バイト数 → a1(戻) = 取っ手 (アドレス)
  MEMORY_RELEASE = 14,   // a1 = 取っ手 (自分のものだけ返せる)
  MEMORY_HAND_OVER = 15, // a1 = 取っ手, a2 = 渡す先 → 持ち主が移る
  MEMORY_OWNER = 16,     // a1 = 取っ手 → a1(戻) = 今の持ち主
  // ---- 名乗り (System Object が起動するまでの暫定の宿) ----
  // ★オブジェクトが**自分で名乗る**。どのオブジェクトとして登録するかは
  //   EXPORT_METHOD と同じく**発行元から導出する**ので、他人の名を騙れない。
  // ★★カーネルオブジェクトは名前を**持って返すだけ**で、**比較は一切しない**。
  //   比較は文字列処理であり、それを入れた瞬間にオブジェクトシステムが定数時間で
  //   なくなる (D26)。名前で引く (resolve) のは System Object の仕事で、
  //   起動したら OBJECT_NAME で全部読み出して自分の索引を作り、引き継ぐ。
  // ★名前は**コピーしない**。文字列リテラル等、系より長生きするものを渡すこと
  //   (flash 上のリテラルは XIP で常に見えており、非特権からも読める)。
  DECLARE_NAME = 17, // a1 = const char*。自分に名を付ける (付け直しは不可)
  OBJECT_NAME = 18,  // a1 = オブジェクト ID → a1(戻) = const char* (0 = 無名)
};

// 生成時に宣言する、そのオブジェクトが必要とする走らせ方。
// ★静的な権限クラスではない (D6) — 「どう走らせるか」の宣言であって、誰が偉いかの
//   話ではない。ペリフェラルを直接叩くオブジェクトだけが PRIVILEGED を宣言し、
//   その上のドライバは非特権のままでいられる (DESIGN §11.2 の分業)。
constexpr uintptr_t OBJECT_PRIVILEGED = 1u << 0;
// ★非特権で走らせる。触れるのは region に張られた場所 (コードとヒープ) だけになり、
//   静的データもペリフェラルもカーネルの簿記も見えなくなる。
//   したがって非特権で走れるオブジェクトは「状態をヒープに置き、標準ライブラリを
//   直に呼ばない」ものに限られる (DESIGN §11.2.2)。当面は宣言した相手だけ。
constexpr uintptr_t OBJECT_UNPRIVILEGED = 1u << 1;

// ★このオブジェクトのスレッドを走らせてよいコアの集合 (0 = どこでもよい)。
//   flags の上位に載せる。**必要なのは「機械の都合で固定されている」相手だけ**で、
//   既定はどこでも走れる — 固定を既定にすると、渡す機構が効いていることを
//   確かめられなくなる (決めた通りに動いただけになる)。
//   実例 (2026-08-21 実測): CYW43 は初期化したコアからしか触れない。blink スレッドが
//   core1 へ移った瞬間に pico-sdk の assert が発火し、そのスレッドが止まった。
//   「気をつけて core0 に置く」ではなく、**オブジェクトの性質として宣言する**。
constexpr uintptr_t OBJECT_AFFINITY_SHIFT = 8;
constexpr uintptr_t OBJECT_AFFINITY_MASK = 0xFFu << OBJECT_AFFINITY_SHIFT;
constexpr uintptr_t OBJECT_ON_CORE(uintptr_t core) {
  return (1u << core) << OBJECT_AFFINITY_SHIFT;
}

// オブジェクトへ返るエラー (a0)。0 = 成功はワイヤ規約 (D12)。
// ★「未知の番号」はここに居る — 番号を解釈するのがオブジェクトランドだから。
//   黙って捨てず必ずこれを返す (DESIGN §11.2.0 の計測事故の教訓)。
enum struct object_error : uintptr_t {
  OK = 0,
  UNKNOWN_API,       // 未知の番号
  BAD_OBJECT,        // オブジェクト ID が範囲外 / 未生成
  BAD_METHOD,        // メソッド番号が範囲外
  UNDECLARED_METHOD, // 未 export のメソッドを呼んだ
  ALREADY_EXISTS,    // 既に生成済みのオブジェクト ID
  NO_STACK,          // 呼び出しフレームを積むスタックが足りない
  UNWIND_REJECTED,   // 巻き戻しがカーネルの検算で弾かれた
  NO_THREAD,         // スレッド枠かスタックが尽きた
  NOT_RUNNABLE,      // 対象スレッドが今は走れない (終了済み / 誰かが持っている)
  KERNEL_REFUSED,    // カーネルがそもそも届けられなかった (KERNEL_ERROR_MARK 付き)
  NO_MEMORY,         // 借りられる記憶が無い
  BAD_MEMORY,        // 取っ手が不正 (借りていない / 範囲外)
  NOT_OWNER,         // 自分のものではない記憶に触ろうとした
  // 自分に残っている実行権が、貸すに足りるだけ無かった。★「相手が走れない」
  // (NOT_RUNNABLE) とは別物 — 相手は走れるが**こちらに配れる持ち分が無い**。
  // 区別しないと、スケジューラが次の候補を延々と試して空回りする。
  NO_TIME,
  ALREADY_NAMED, // 名は付け直せない (誰かが控えた名が別物を指すようになるため)
};

} // namespace shizuku
#endif // SHIZUKU_OBJECT_API_HPP
