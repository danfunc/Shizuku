#ifndef SHIZUKU_OBJECT_API_HPP
#define SHIZUKU_OBJECT_API_HPP
#include <cstdint>

// ===========================================================================
//  オブジェクトランドの API — カーネルオブジェクトが提供する syscall の語彙
// ===========================================================================
//  ★番号を持つのはここだけ。カーネルは番号を一切知らない (I-1) ので、この
//    ヘッダはカーネル側からは参照されない。
//  形は a0 = 番号, a1..a4 = 引数 / 戻り a0 = エラー (0 = 成功), a1 = 値。
//  ★将来 XNO (オブジェクト集合の別リポジトリ, D17) が使う公開 ABI はこれ。
//    今は internal_headers に置いているが、境界を切るときにここから公開ヘッダへ移す。
namespace shizuku {

enum struct object_api : uintptr_t {
  // オブジェクトを 1 つ作る。a1 = オブジェクト ID, a2 = main の入口,
  // a3 = object_flags のビット和。
  // ★最初のメソッドは生成側 (合成する側) が与える。オブジェクト自身はまだ一度も
  //   走っていないので自分では登録できない — 「方針は合成側」の最初の現れ。
  CREATE_OBJECT = 1,
  // メソッドから戻る。a1 = 畳む呼び出し段数 (1 = 自分だけ), a2 = 戻り値,
  // a3 = エラーコード。
  // ★★この番号は**カーネルの RETURN と同じ値**にしてある。カーネルが呼び先の lr へ
  //   載せる戻り口は常に RETURN を撃つが、同じ svc が誰から出たかで意味が変わる:
  //   ハンドラから出れば巻き戻しプリミティブ、オブジェクトから出れば経路判定で
  //   ここへ届き「メソッドが戻った」という知らせになる。だから戻り口は 1 本でよく、
  //   呼び出しごとに戻り口を指定する必要も無い。
  //   何フレーム落とすかは受けたこちらが決める (1 段 = トランポリン枠 + 呼び先枠)。
  EXIT_METHOD = 2,
  // 自分のメソッドを公開する。a1 = メソッド番号, a2 = 入口。
  // 誰のものとして登録するかは**発行元から導出**する (名乗らせない)。
  // 2 個目以降のメソッドを増やすときに使う (1 個目は CREATE_OBJECT が据える)。
  EXPORT_METHOD = 3,
  // 他オブジェクトのメソッドを呼ぶ。a1 = オブジェクト ID, a2 = メソッド番号,
  // a3 = 引数。戻り a1 = メソッドの戻り値。
  CALL_METHOD = 4,
  // 今どのオブジェクトとして走っているか / 誰に呼ばれたか。戻り a1 = オブジェクト ID。
  // ★identity はカーネルではなくカーネルオブジェクトの台帳から答える
  //   (PORT §3.1「呼び出し元 identity はカーネル支援不要」)。
  GET_CURRENT_OBJECT = 5,
  GET_CALLER_OBJECT = 6,
  // オブジェクトのメソッドを**別のスレッドとして**起動する。
  // a1 = オブジェクト ID, a2 = メソッド番号, a3 = 引数。戻り a1 = スレッド ID。
  // ★呼び出し (CALL_METHOD) と違って戻りを待たない。「イベントを待つコードを
  //   書かせない」ためには、待つ側ではなく呼ばれる側になれる必要がある (§4.3)。
  SPAWN = 7,
  // 実行権を譲る。a1 = 0 なら次の走れるスレッドへ、非 0 ならその ID へ。
  // ★借り手として走っている最中なら、これは貸し手への早期復帰になる。
  YIELD = 8,
  // 実行権を時限つきで貸す。a1 = スレッド ID, a2 = 期限 [µs]。
  // 戻り a1 = 0 なら期限切れで取り上げ、1 なら相手が自分から返した。
  // ★期限は quantum ではなく安全網。正常時は相手が期限より早く返すので発火しない。
  RUN_FOR = 9,
  // 自分のスレッドを終える。a1 = 終了コード。
  EXIT_THREAD = 10,
  // 締切まで自分を走らせない。a1 = µs。**待っている間は他へ CPU を渡す**ので、
  // 「待つ」ことが他の仕事を止めない (協調の要)。
  SLEEP_US = 11,
  // スケジューラがそのスレッドへ CPU を渡すときの時限 [µs]。a1 = スレッド, a2 = µs。
  // 0 = 期限なし (バトン渡し。自分から返さないと戻ってこない = 凍結の面になる)。
  // ★これは方針。期限つきで渡す限り、自分から返さないスレッドがいても系は凍らない。
  SET_BUDGET = 12,
};

// 生成時に宣言する、そのオブジェクトが必要とする走らせ方。
// ★静的な権限クラスではない (D6) — 「どう走らせるか」の宣言であって、誰が偉いかの
//   話ではない。ペリフェラルを直接叩くオブジェクトだけが PRIVILEGED を宣言し、
//   その上のドライバは非特権のままでいられる (DESIGN §11.2 の分業)。
constexpr uintptr_t OBJECT_PRIVILEGED = 1u << 0;

// オブジェクトへ返るエラー (a0)。0 = 成功はワイヤ規約 (D12)。
// ★「未知の番号」はここに居る — 番号を解釈するのがオブジェクトランドだから。
//   黙って捨てず必ずこれを返す (DESIGN §11.2.0 の計測事故の教訓)。
enum struct object_error : uintptr_t {
  OK = 0,
  UNKNOWN_API,       // 未知の番号
  BAD_OBJECT,        // オブジェクト ID が範囲外 / 未生成
  BAD_METHOD,        // メソッド番号が範囲外
  UNDECLARED_METHOD, // 未 export のメソッドを呼んだ
  ALREADY_EXISTS,    // 既に生成済みのオブジェクト ID
  NO_STACK,          // 呼び出しフレームを積むスタックが足りない
  UNWIND_REJECTED,   // 巻き戻しがカーネルの検算で弾かれた
  NO_THREAD,         // スレッド枠かスタックが尽きた
  NOT_RUNNABLE,      // 対象スレッドが今は走れない (終了済み / 誰かが持っている)
  KERNEL_REFUSED,    // カーネルがそもそも届けられなかった (KERNEL_ERROR_MARK 付き)
};

} // namespace shizuku
#endif // SHIZUKU_OBJECT_API_HPP
